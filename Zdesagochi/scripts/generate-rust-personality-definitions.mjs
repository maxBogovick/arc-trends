import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const root = process.cwd();
const sourcePath = join(root, 'packages/personality-pet-preset/src/personalities.ts');
const targetPath = join(root, 'backend/src/engine/personality_definitions.rs');

const source = await readFile(sourcePath, 'utf8');
const personalities = extractPersonalities(source);
const rendered = renderRustModule(personalities);

if (process.argv.includes('--check')) {
  const current = await readFile(targetPath, 'utf8').catch(() => '');
  if (normalizeRust(current) !== normalizeRust(rendered)) {
    console.error(`${targetPath} is stale. Run npm run generate:rust-personality-definitions.`);
    process.exit(1);
  }
  console.log('PASS - Rust personality definitions are generated from TS preset');
} else {
  await writeFile(targetPath, rendered);
  console.log(`Generated ${targetPath}`);
}

function extractPersonalities(text) {
  const defaultMoodBias = extractConstObject(text, 'DEFAULT_MOOD_BIAS');
  const marker = 'export const PERSONALITIES';
  const start = text.indexOf(marker);
  if (start === -1) throw new Error(`Missing PERSONALITIES in ${sourcePath}`);

  const equals = text.indexOf('=', start);
  if (equals === -1) throw new Error('Missing PERSONALITIES assignment');

  const arrayStart = text.indexOf('[', equals);
  if (arrayStart === -1) throw new Error('Missing PERSONALITIES array literal');

  let depth = 0;
  for (let index = arrayStart; index < text.length; index++) {
    const char = text[index];
    if (char === '[') depth++;
    if (char === ']') depth--;
    if (depth === 0) {
      const literal = text.slice(arrayStart, index + 1);
      return Function('DEFAULT_MOOD_BIAS', `"use strict"; return (${literal});`)(defaultMoodBias);
    }
  }

  throw new Error('Unterminated PERSONALITIES array literal');
}

function extractConstObject(text, name) {
  const marker = `const ${name} = `;
  const start = text.indexOf(marker);
  if (start === -1) throw new Error(`Missing ${name} in ${sourcePath}`);

  const objectStart = text.indexOf('{', start + marker.length);
  if (objectStart === -1) throw new Error(`Missing object literal for ${name}`);

  let depth = 0;
  for (let index = objectStart; index < text.length; index++) {
    const char = text[index];
    if (char === '{') depth++;
    if (char === '}') depth--;
    if (depth === 0) {
      const literal = text.slice(objectStart, index + 1);
      return Function(`"use strict"; return (${literal});`)();
    }
  }

  throw new Error(`Unterminated object literal for ${name}`);
}

function renderRustModule(personalities) {
  return `// @generated by scripts/generate-rust-personality-definitions.mjs
// Source of truth: packages/personality-pet-preset/src/personalities.ts

use std::collections::HashMap;

use crate::engine::types::{
    AutoSleepConfig, EmergentTrigger, FoodPreferences, MoodBiasConfig, PersonalityDefinition,
    PersonalitySpecialRules,
};

pub fn build_personalities() -> Vec<PersonalityDefinition> {
    vec![
${personalities.map(renderPersonality).join('\n')}
    ]
}

fn hm<const N: usize>(pairs: [(&'static str, f64); N]) -> HashMap<String, f64> {
    pairs.iter().map(|(k, v)| (k.to_string(), *v)).collect()
}

fn sm<const N: usize>(
    pairs: [(&'static str, HashMap<String, f64>); N],
) -> HashMap<String, HashMap<String, f64>> {
    pairs.into_iter().map(|(k, v)| (k.to_string(), v)).collect()
}
`;
}

function renderPersonality(personality) {
  return `        PersonalityDefinition {
            id: ${rs(personality.id)},
            name: ${rs(personality.name)},
            tagline: ${rs(personality.tagline)},
            description: ${rs(personality.description)},
            emoji: ${rs(personality.emoji)},
            rarity: ${rs(personality.rarity)},
            linked_skin_ids: ${stringVec(personality.linkedSkinIds)},
            decay_rates: ${map(personality.decayRates)},
            restore_bonus: ${nestedMap(personality.restoreBonus)},
            xp_multipliers: ${map(personality.xpMultipliers)},
            coin_multipliers: ${map(personality.coinMultipliers)},
            food_preferences: FoodPreferences {
                loved_ids: ${stringVec(personality.foodPreferences.lovedIds)},
                hated_ids: ${stringVec(personality.foodPreferences.hatedIds)},
                love_bonus: ${map(personality.foodPreferences.loveBonus)},
                hate_penalty: ${map(personality.foodPreferences.hatePenalty)},
                universal_feed_bonus: ${optionalMap(personality.foodPreferences.universalFeedBonus)},
            },
            auto_sleep: AutoSleepConfig {
                enabled: ${personality.autoSleep.enabled},
                energy_threshold: ${float(personality.autoSleep.energyThreshold)},
                probability: ${float(personality.autoSleep.probability)},
            },
            mood_bias: MoodBiasConfig {
                ecstatic_min_avg: ${float(personality.moodBias.ecstaticMinAvg)},
                happy_min_avg: ${float(personality.moodBias.happyMinAvg)},
                content_min_avg: ${float(personality.moodBias.contentMinAvg)},
            },
            natural_health_regen: ${float(personality.naturalHealthRegen)},
            negative_effect_resistance: ${float(personality.negativeEffectResistance)},
            possible_flags: ${stringVec(personality.possibleFlags)},
            emergent_triggers: vec![${(personality.emergentTriggers ?? []).map(renderTrigger).join(', ')}],
            special_rules: ${optionalSpecialRules(personality.specialRules)},
        },`;
}

function renderTrigger(trigger) {
  return `EmergentTrigger { state_type: ${rs(trigger.stateType)}, description: ${rs(trigger.description)} }`;
}

function optionalSpecialRules(rules) {
  if (rules === undefined) return 'None';
  const fields = [
    ['passiveStatBonusWhenFull', 'passive_stat_bonus_when_full', boolOpt],
    ['rejectSleepWhenEnergized', 'reject_sleep_when_energized', boolOpt],
    ['peakPerformanceThreshold', 'peak_performance_threshold', numberOpt],
    ['anxiousStatSadThreshold', 'anxious_stat_sad_threshold', numberOpt],
    ['nighttimeHours', 'nighttime_hours', hoursOpt],
    ['nightEnergyDecayDisabled', 'night_energy_decay_disabled', boolOpt],
    ['resistsBathing', 'resists_bathing', boolOpt],
    ['xpEveryOtherAction', 'xp_every_other_action', boolOpt],
    ['randomizeDailySeed', 'randomize_daily_seed', boolOpt],
    ['flatXpFromPlay', 'flat_xp_from_play', boolOpt],
    ['foodBoredomEnabled', 'food_boredom_enabled', boolOpt],
    ['healRefuseHealthThreshold', 'heal_refuse_health_threshold', numberOpt],
    ['feedRestoreByPhase', 'feed_restore_by_phase', boolOpt],
    ['trustThresholdBonds', 'trust_threshold_bonds', integerOpt],
  ];

  return `Some(PersonalitySpecialRules {
                ${fields.map(([tsKey, rsKey, render]) => `${rsKey}: ${render(rules[tsKey])},`).join('\n                ')}
            })`;
}

function boolOpt(value) {
  return value === undefined ? 'None' : `Some(${value})`;
}

function numberOpt(value) {
  return value === undefined ? 'None' : `Some(${float(value)})`;
}

function integerOpt(value) {
  return value === undefined ? 'None' : `Some(${value})`;
}

function hoursOpt(value) {
  return value === undefined ? 'None' : `Some([${value[0]}, ${value[1]}])`;
}

function optionalMap(value) {
  return value === undefined ? 'None' : `Some(${map(value)})`;
}

function nestedMap(value) {
  const entries = Object.entries(value ?? {});
  if (entries.length === 0) return 'HashMap::new()';
  return `sm([${entries.map(([key, nested]) => `(${rsRaw(key)}, ${map(nested)})`).join(', ')}])`;
}

function map(value) {
  const entries = Object.entries(value ?? {});
  if (entries.length === 0) return 'HashMap::new()';
  return `hm([${entries.map(([key, number]) => `(${rsRaw(key)}, ${float(number)})`).join(', ')}])`;
}

function stringVec(values) {
  return `vec![${(values ?? []).map(rs).join(', ')}]`;
}

function rs(value) {
  return `${JSON.stringify(value)}.to_string()`;
}

function rsRaw(value) {
  return JSON.stringify(value);
}

function float(value) {
  if (!Number.isFinite(value)) throw new Error(`Invalid numeric value: ${value}`);
  return Number.isInteger(value) ? `${value}.0` : String(value);
}

function normalizeRust(text) {
  return text.replace(/\s+/g, '');
}
