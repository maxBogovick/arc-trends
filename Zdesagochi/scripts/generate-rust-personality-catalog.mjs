import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const root = process.cwd();
const sourcePath = join(root, 'packages/personality-core/src/personalityCatalog.ts');
const targetPath = join(root, 'backend/src/engine/personality_catalog.rs');

const source = await readFile(sourcePath, 'utf8');
const traitHomes = extractConstObject(source, 'PERSONALITY_TRAIT_HOMES');
const behaviorEvidence = extractConstObject(source, 'PERSONALITY_BEHAVIOR_EVIDENCE');
const rendered = renderRustModule(traitHomes, behaviorEvidence);

if (process.argv.includes('--check')) {
  const current = await readFile(targetPath, 'utf8').catch(() => '');
  if (normalizeRust(current) !== normalizeRust(rendered)) {
    console.error(`${targetPath} is stale. Run npm run generate:rust-personality-catalog.`);
    process.exit(1);
  }
  console.log('PASS - Rust personality catalog is generated from TS source');
} else {
  await writeFile(targetPath, rendered);
  console.log(`Generated ${targetPath}`);
}

function extractConstObject(text, name) {
  const marker = `export const ${name} = `;
  const start = text.indexOf(marker);
  if (start === -1) throw new Error(`Missing ${name} in ${sourcePath}`);

  const objectStart = text.indexOf('{', start + marker.length);
  if (objectStart === -1) throw new Error(`Missing object literal for ${name}`);

  let depth = 0;
  for (let index = objectStart; index < text.length; index++) {
    const char = text[index];
    if (char === '{') depth++;
    if (char === '}') depth--;
    if (depth === 0) {
      const literal = text.slice(objectStart, index + 1);
      return Function(`"use strict"; return (${literal});`)();
    }
  }

  throw new Error(`Unterminated object literal for ${name}`);
}

function renderRustModule(traitHomes, behaviorEvidence) {
  const ids = Object.keys(traitHomes);
  const cases = ids.map(id => renderPositionCase(id, traitHomes[id])).join('\n');
  const radiusCases = ids.map(id => `        "${id}" => ${float(traitHomes[id].radiusBase)},`).join('\n');
  const evidenceCases = Object.keys(behaviorEvidence)
    .map(id => renderEvidenceCase(id, behaviorEvidence[id]))
    .join('\n');

  return `// @generated by scripts/generate-rust-personality-catalog.mjs
// Source of truth: packages/personality-core/src/personalityCatalog.ts

use std::collections::HashMap;

use crate::engine::types::{BehaviorAxis, TraitKey, TraitVector};

pub fn personality_position(id: &str) -> TraitVector {
    let mut map: HashMap<TraitKey, f64> = HashMap::new();
    match id {
${cases}
        _ => {
            for &key in TraitKey::all() {
                map.insert(key, 50.0);
            }
        }
    }
    map
}

pub fn personality_radius_base(id: &str) -> f64 {
    match id {
${radiusCases}
        _ => 22.0,
    }
}

pub fn behavior_evidence_for_personality(
    axes: &HashMap<BehaviorAxis, f64>,
    personality_id: &str,
) -> f64 {
    let axis = |key: BehaviorAxis| axes.get(&key).copied().unwrap_or(0.0);

    match personality_id {
${evidenceCases}
        _ => 0.0,
    }
}
`;
}

function renderPositionCase(id, home) {
  const position = home.position;
  return `        "${id}" => {
            map.insert(TraitKey::Vitality, ${float(position.vitality)});
            map.insert(TraitKey::Sociality, ${float(position.sociality)});
            map.insert(TraitKey::Order, ${float(position.order)});
            map.insert(TraitKey::Appetite, ${float(position.appetite)});
            map.insert(TraitKey::Caution, ${float(position.caution)});
            map.insert(TraitKey::Curiosity, ${float(position.curiosity)});
        }`;
}

function renderEvidenceCase(id, evidence) {
  const terms = [];

  for (const [axis, weight] of Object.entries(evidence.axes ?? {})) {
    terms.push(`${axisExpr(axis)} * ${float(weight)}`);
  }

  for (const [axis, rule] of Object.entries(evidence.lowAxes ?? {})) {
    terms.push(`(${float(rule.below)} - ${axisExpr(axis)}).max(0.0) * ${float(rule.weight)}`);
  }

  const inline = terms.join(' + ');
  if (terms.length <= 2 && !inline.includes('.max(')) {
    return `        "${id}" => ${inline},`;
  }

  return `        "${id}" => {
            ${terms.join('\n                + ')}
        }`;
}

function axisExpr(axis) {
  return `axis(BehaviorAxis::${toRustEnumCase(axis)})`;
}

function toRustEnumCase(value) {
  return value
    .split('_')
    .map(part => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function float(value) {
  if (!Number.isFinite(value)) throw new Error(`Invalid numeric value: ${value}`);
  return Number.isInteger(value) ? `${value}.0` : String(value);
}

function normalizeRust(text) {
  return text.replace(/\s+/g, '');
}
